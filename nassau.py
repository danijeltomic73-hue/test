"""
POKEMON NASSAU - Alle Werkzeuge in einer Datei.

Privater ROM-Hack auf Basis von pokegold. Diese Datei buendelt alle
Patch-Skripte und Pruefwerkzeuge, damit nur eine Datei verwaltet werden muss.
Die eingebetteten Skripte sind unveraendert und einzeln getestet.

AUFRUFE
  python3 nassau.py patch <pokegold-ordner> [seed]
      Spielt alle Nassau-Inhalte ein (Bierstadt, Welt, Texte, Menues, Randomizer)
      und laesst anschliessend den Zeichencheck laufen.

  python3 nassau.py pruefen <pokegold-ordner>
      Nur Zeichencheck (unbekannte Zeichen im GB-Zeichensatz).

  python3 nassau.py karte-pruefen <pokegold-ordner> <MapName> <breite> <hoehe> <tileset>
      Prueft Tueren, Schilder, NPC-Positionen und Erreichbarkeit einer Karte.
      Beispiel: python3 nassau.py karte-pruefen build/pokegold NewBarkTown 20 18 johto

  python3 nassau.py karte-bild <pokegold-ordner> <blk-datei> <breite> <tileset> <out.png>
      Rendert eine Karte als farbiges PNG (Tagespaletten). Braucht Pillow.

  python3 nassau.py stufe <name> <pokegold-ordner> [seed]
      Einzelne Stufe anwenden. Namen: bierstadt, welt, texte, menue, random
"""
import sys, pathlib, runpy, tempfile, os, base64

# Reihenfolge der Patch-Stufen - nicht aendern, sie bauen aufeinander auf.
STUFEN = ["bierstadt", "welt", "texte", "menue", "random"]

ZUORDNUNG = {
    "bierstadt": "nassau_bierstadt.py",
    "welt":      "nassau_gold.py",
    "texte":     "nassau_texte.py",
    "menue":     "nassau_menue.py",
    "random":    "nassau_gold_random.py",
    "zeichen":   "zeichencheck.py",
    "karte":     "kartencheck.py",
    "bild":      "blkview.py",
}


def lauf(name, argumente):
    """Fuehrt ein eingebettetes Skript mit den uebergebenen Argumenten aus."""
    quelltext = base64.b64decode(SKRIPTE[ZUORDNUNG[name]]).decode("utf-8")
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False,
                                     encoding="utf-8") as f:
        f.write(quelltext)
        pfad = f.name
    alt = sys.argv
    try:
        sys.argv = [pfad] + [str(a) for a in argumente]
        runpy.run_path(pfad, run_name="__main__")
    finally:
        sys.argv = alt
        os.unlink(pfad)


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    befehl = sys.argv[1]
    rest = sys.argv[2:]

    if befehl == "patch":
        if not rest:
            print("Fehlt: Pfad zum pokegold-Ordner."); return 1
        ziel = rest[0]
        seed = rest[1] if len(rest) > 1 else "20260802"
        if not pathlib.Path(ziel, "Makefile").exists():
            print(f"FEHLER: {ziel} sieht nicht nach einem pokegold-Checkout aus.")
            return 1
        for stufe in STUFEN:
            args = [ziel, seed] if stufe == "random" else [ziel]
            lauf(stufe, args)
        lauf("zeichen", [ziel])
        print("Alle Nassau-Inhalte eingespielt.")
        return 0

    if befehl == "stufe":
        if len(rest) < 2:
            print("Aufruf: nassau.py stufe <name> <pokegold-ordner> [seed]"); return 1
        name, ziel = rest[0], rest[1]
        if name not in STUFEN:
            print(f"Unbekannte Stufe {name!r}. Moeglich: {', '.join(STUFEN)}"); return 1
        args = [ziel, rest[2] if len(rest) > 2 else "20260802"] if name == "random" else [ziel]
        lauf(name, args)
        return 0

    if befehl == "pruefen":
        if not rest:
            print("Fehlt: Pfad zum pokegold-Ordner."); return 1
        lauf("zeichen", rest)
        return 0

    if befehl == "karte-pruefen":
        if len(rest) < 5:
            print("Aufruf: nassau.py karte-pruefen <ordner> <MapName> <breite> <hoehe> <tileset>")
            return 1
        lauf("karte", rest)
        return 0

    if befehl == "karte-bild":
        if len(rest) < 5:
            print("Aufruf: nassau.py karte-bild <ordner> <blk-datei> <breite> <tileset> <out.png>")
            return 1
        lauf("bild", rest)
        return 0

    print(f"Unbekannter Befehl {befehl!r}.")
    print(__doc__)
    return 1


